# Run from repository root: Rscript scripts/R/05-independent-t-test.R
# Base R only. Uses the supplied complete synthetic teaching dataset.
dat <- read.csv("data/example/05-two-group-scores.csv",
                stringsAsFactors = FALSE)
stopifnot(all(c("learner_id", "approach", "score") %in% names(dat)))
stopifnot(!anyNA(dat), !anyDuplicated(dat$learner_id))
stopifnot(all(nzchar(trimws(dat$learner_id))))
stopifnot(setequal(unique(dat$approach), c("A", "B")))
stopifnot(is.numeric(dat$score), all(is.finite(dat$score)))
stopifnot(all(dat$score >= 0 & dat$score <= 100))

# Explicit order makes every difference A minus B.
a <- dat$score[dat$approach == "A"]
b <- dat$score[dat$approach == "B"]
stopifnot(length(a) >= 2, length(b) >= 2, sd(a) > 0, sd(b) > 0)
fit <- t.test(a, b, alternative = "two.sided", var.equal = FALSE,
              conf.level = 0.95)

# Welch standard error and Satterthwaite degrees of freedom.
va <- var(a) / length(a)
vb <- var(b) / length(b)
se <- sqrt(va + vb)
welch_df <- (va + vb)^2 /
  (va^2 / (length(a) - 1) + vb^2 / (length(b) - 1))
stopifnot(isTRUE(all.equal(unname(fit$parameter), welch_df)))
summary_result <- data.frame(
  n_A = length(a), n_B = length(b),
  mean_A = mean(a), mean_B = mean(b), sd_A = sd(a), sd_B = sd(b),
  difference_A_minus_B = mean(a) - mean(b), standard_error = se,
  ci_lower = unname(fit$conf.int[1]), ci_upper = unname(fit$conf.int[2]),
  t = unname(fit$statistic), df = unname(fit$parameter), p_value = fit$p.value
)
print(fit)
print(summary_result)
dir.create("results/tables", recursive = TRUE, showWarnings = FALSE)
write.csv(summary_result, "results/tables/05-welch-t-test.csv", row.names = FALSE)

# Diagnostics are generated by this script, separately from Quarto.
dir.create("results/figures", recursive = TRUE, showWarnings = FALSE)
png("results/figures/05-group-diagnostics.png", width = 1800,
    height = 650, res = 150)
par(mfrow = c(1, 3))
stripchart(list(A = a, B = b), method = "stack", vertical = TRUE,
           pch = 19, col = c("#087f8c", "#b86e13"),
           ylab = "Score (points)", xlab = "Approach", main = "Observed scores")
qqnorm(a, pch = 19, col = "#087f8c", main = "Normal Q-Q: A")
qqline(a)
qqnorm(b, pch = 19, col = "#b86e13", main = "Normal Q-Q: B")
qqline(b)
invisible(dev.off())

png("results/figures/05-mean-difference.png", width = 1100,
    height = 650, res = 150)
par(mar = c(5, 4, 4, 2) + 0.1)
limits <- range(c(fit$conf.int, 0)) + c(-1, 1)
plot(mean(a) - mean(b), 1, xlim = limits, ylim = c(0.5, 1.5),
     yaxt = "n", ylab = "", xlab = "Mean difference: A minus B (points)",
     main = "Estimated difference and 95% Welch confidence interval",
     pch = 19, col = "#087f8c")
abline(v = 0, lty = 2, col = "gray50")
segments(fit$conf.int[1], 1, fit$conf.int[2], 1, lwd = 3, col = "#087f8c")
points(mean(a) - mean(b), 1, pch = 19, col = "#087f8c")
invisible(dev.off())
